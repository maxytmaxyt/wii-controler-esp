static void sdp_event_handler(esp_sdp_cb_event_t event,
                              esp_sdp_cb_param_t *param)
{
    if (event != ESP_SDP_INIT_EVT) {
        return;
    }

    if (param->init.status != ESP_SDP_SUCCESS) {
        ESP_LOGE(TAG, "SDP initialization failed: %d", param->init.status);
        return;
    }

    esp_bluetooth_sdp_record_t record = {
        .dip = {
            .hdr = {
                .type = ESP_SDP_TYPE_DIP_SERVER,
            },
            .vendor = WIIMOTE_VENDOR_ID,
            .vendor_id_source = ESP_SDP_VENDOR_ID_SRC_BT,
            .product = WIIMOTE_PRODUCT_ID,
            .version = WIIMOTE_VERSION,
            .primary_record = true,
        },
    };

    esp_err_t ret = esp_sdp_create_record(&record);
    if (ret != ESP_OK) {
        ESP_LOGE(TAG, "PnP SDP record registration failed: %s",
                 esp_err_to_name(ret));
    }
}

esp_err_t wiimote_sdp_register(void)
{
    esp_err_t ret = esp_sdp_register_callback(sdp_event_handler);
    if (ret != ESP_OK) {
        ESP_LOGE(TAG, "SDP callback registration failed: %s",
                 esp_err_to_name(ret));
        return ret;
    }

    ret = esp_sdp_init();
    if (ret != ESP_OK) {
        ESP_LOGE(TAG, "SDP initialization failed: %s", esp_err_to_name(ret));
    }
    return ret;
}
